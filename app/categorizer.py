"""Рубрикация новостей по ключевым словам.

Категория определяется первым сработавшим правилом (порядок = приоритет).
Функция is_macro_relevant() дополнительно используется для общих лент
информагентств (ТАСС, Интерфакс), чтобы отбирать только макроэкономические
сообщения, касающиеся России.
"""
import re

# (категория, [регулярные выражения])
RULES: list[tuple[str, list[str]]] = [
    ("ставка ЦБ", [
        r"ключев\w+ став(?:к|ок)",
        r"став(?:к\w*|ок) рефинансировани",
        r"денежно-кредитн",
        r"\bдкп\b",
        r"key rate",
        r"совет\w* директоров банка россии.{0,40}став(?:к|ок)",
    ]),
    ("инфляция", [
        r"инфляци",
        r"дефляци",
        r"\bипц\b",
        r"индекс\w* потребительск\w+ цен",
        r"рост\w? потребительск\w+ цен",
        r"инфляционн\w+ ожидани",
    ]),
    ("ВВП", [
        r"\bввп\b",
        r"валов\w+ внутренн\w+ продукт",
        r"экономическ\w+ рост",
        r"промышленн\w+ производств",
        r"делов\w+ активност",
    ]),
    ("курс валют", [
        r"курс\w? (доллар|евро|юан|рубл|валют)",
        r"(доллар|евро|юан|рубл)\w* .{0,30}курс",
        r"валютн\w+ (рынок|курс|интервенц)",
        r"(укреплени|ослаблени|обвал|падени)\w* рубл",
        r"официальн\w+ курс",
    ]),
    ("санкции", [
        r"санкци",
        r"контрсанкц",
        r"\bsdn\b",
        r"эмбарго",
        r"потол\w+ цен",
        r"заморо\w+ (актив|резерв)",
    ]),
    ("резервы", [
        r"золотовалютн",
        r"международн\w+ резерв",
        r"\bфнб\b",
        r"фонд\w? национального благосостояния",
        r"золот\w+ запас",
    ]),
    ("бюджет и налоги", [
        r"бюджет",
        r"налог",
        r"\bндс\b",
        r"\bндфл\b",
        r"госдолг",
        r"\bофз\b",
        r"казначейств",
        r"минфин\w* размест",
    ]),
    ("банковский сектор", [
        r"банковск\w+ (сектор|систем)",
        r"кредитовани",
        r"ипотек",
        r"вклад\w{0,3}\b",
        r"депозит",
        r"максимальн\w+ процентн\w+ став(?:к|ок)",
        r"отозв\w+ лицензи",
        r"микрофинанс",
    ]),
    ("финансовые рынки", [
        r"мосбирж",
        r"московск\w+ бирж",
        r"фондов\w+ рынок",
        r"облигаци",
        r"\bipo\b",
        r"\bртс\b",
        r"рынок акций",
        r"ценн\w+ бумаг",
    ]),
]

DEFAULT_CATEGORY = "прочее"
CATEGORIES = [name for name, _ in RULES] + [DEFAULT_CATEGORY]

# Общемакроэкономические маркеры для фильтра релевантности лент информагентств.
_MACRO_EXTRA = [
    r"центробанк",
    r"банк\w? росси",
    r"\bцб\b",
    r"минфин",
    r"росстат",
    r"минэкономразвити",
    r"макроэконом",
    r"экономик\w+ (росси|рф)",
    r"российск\w+ экономик",
    r"экспорт",
    r"импорт",
    r"торгов\w+ баланс",
    r"платежн\w+ баланс",
    r"безработиц",
    r"реальн\w+ доход",
    r"госзакупк",
    r"тариф",
]

_compiled_rules = [
    (name, [re.compile(p, re.IGNORECASE) for p in patterns])
    for name, patterns in RULES
]
_compiled_extra = [re.compile(p, re.IGNORECASE) for p in _MACRO_EXTRA]


def categorize(text: str) -> str:
    """Возвращает категорию для текста (заголовок + summary)."""
    for name, patterns in _compiled_rules:
        if any(p.search(text) for p in patterns):
            return name
    return DEFAULT_CATEGORY


def is_macro_relevant(text: str) -> bool:
    """Относится ли текст к макроэкономике России (для общих новостных лент)."""
    if categorize(text) != DEFAULT_CATEGORY:
        return True
    return any(p.search(text) for p in _compiled_extra)
